/** 按首字索引（接龙用） */
const CHAIN_INDEX = new Map<string, Idiom[]>()
for (const it of IDIOMS) {
  const first = it.idiom[0]
  const arr = CHAIN_INDEX.get(first) ?? []
  arr.push(it)
  CHAIN_INDEX.set(first, arr)
}

/** 找出可以接在 idiom 末字后面的成语（不含它自身） */
export function findChain(idiom: string): Idiom[] {
  const last = idiom[idiom.length - 1]
  return (CHAIN_INDEX.get(last) ?? []).filter((x) => x.idiom !== idiom)
}

/** "补全释义"题库：key 必须真实出现在释义原文里，挖空才有效 */
export const MEANING_POOL: Idiom[] = IDIOMS.filter(
  (it) => it.key && it.key.length >= 2 && it.meaning.includes(it.key)
)

/** 随机工具：从数组取 n 个不重复元素 */
export function sample<T>(arr: T[], n: number): T[] {
  const pool = [...arr]
  const out: T[] = []
  while (out.length < n && pool.length > 0) {
    const i = Math.floor(Math.random() * pool.length)
    out.push(pool.splice(i, 1)[0])
  }
  return out
}
